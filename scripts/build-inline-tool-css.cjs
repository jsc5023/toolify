#!/usr/bin/env node
/*
 * Generates the first-paint CSS for the Toolify reading-page tools.
 *
 * Source of truth: style.css, home.css, and tools/<tool>/<tool>.css.
 * The HTML block between TOOLIFY_INLINE_CSS_START/END is generated output.
 */
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const toolsRoot = path.join(root, 'tools');
const excluded = new Set([
  'chmod-calculator',
  'electricity-simulator',
  'date-calculator',
  'unit-converter',
  'geun-gwan-don',
  'money-converter',
  'unix-timestamp',
  'url-parser',
  'privacy-mask',
  'hanja-number-converter',
  'number-baseball',
]);
const checkOnly = process.argv.includes('--check');

function targetTools() {
  return fs.readdirSync(toolsRoot, { withFileTypes: true })
    .filter(entry => entry.isDirectory() && !excluded.has(entry.name))
    .map(entry => entry.name)
    .filter(tool => fs.existsSync(path.join(toolsRoot, tool, 'index.html')))
    .sort();
}

function read(file) {
  return fs.readFileSync(file, 'utf8').replace(/^\uFEFF/, '');
}

function generatedBlock(tool) {
  const cssFiles = [
    ['style.css', path.join(root, 'style.css')],
    ['home.css', path.join(root, 'home.css')],
    [`tools/${tool}/${tool}.css`, path.join(toolsRoot, tool, `${tool}.css`)],
  ];
  for (const [, file] of cssFiles) {
    if (!fs.existsSync(file)) throw new Error(`${tool}: source CSS is missing: ${path.relative(root, file)}`);
  }
  const css = cssFiles.map(([label, file]) => `/* ${label} */\n${read(file).trimEnd()}`).join('\n\n');
  return [
    '    <!-- TOOLIFY_INLINE_CSS_START: generated by scripts/build-inline-tool-css.cjs; do not edit -->',
    `    <style id="toolify-inline-css-${tool}">`,
    css,
    '    </style>',
    '    <!-- TOOLIFY_INLINE_CSS_END -->',
  ].join('\n');
}

function removeOldCss(html, tool) {
  const generated = /\s*<!-- TOOLIFY_INLINE_CSS_START[\s\S]*?<!-- TOOLIFY_INLINE_CSS_END -->/;
  const legacy = new RegExp(`\\s*<style\\s+id=["']${tool}-initial-css["'][^>]*>[\\s\\S]*?<\\/style>`, 'i');
  let result = html.replace(generated, '').replace(legacy, '');
  const removable = new Set([
    '../../style.css',
    '../../home.css',
    '../new-layout-stability.css',
    `./${tool}.css`,
  ]);
  result = result.replace(/^\s*<link\b[^>]*\brel=["']stylesheet["'][^>]*>\s*\r?\n/gim, tag => {
    const href = tag.match(/\bhref=["']([^"']+)["']/i)?.[1]?.split('?')[0];
    return removable.has(href) ? '' : tag;
  });
  return result;
}

let changed = 0;
for (const tool of targetTools()) {
  const htmlFile = path.join(toolsRoot, tool, 'index.html');
  const original = read(htmlFile);
  const withoutOldCss = removeOldCss(original, tool);
  const next = withoutOldCss.replace(/(<meta\s+name=["']viewport["'][^>]*>)/i, `$1\n${generatedBlock(tool)}`);
  if (next === withoutOldCss) throw new Error(`${tool}: viewport meta tag was not found`);
  if (next !== original) {
    changed += 1;
    if (!checkOnly) fs.writeFileSync(htmlFile, next);
    console.log(`${checkOnly ? 'would update' : 'updated'} tools/${tool}/index.html`);
  }
}

console.log(`${checkOnly ? 'check' : 'build'} complete: ${targetTools().length} targets, ${changed} ${checkOnly ? 'would change' : 'changed'}.`);
if (checkOnly && changed) process.exitCode = 1;
